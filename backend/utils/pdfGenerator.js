/**
 * Generate PDF Report for Dashboard/Inventory Summary
 */
export const generateInventoryReportPDF = (data, callback) => {
  const doc = new PDFDocument({ margin: 50, size: 'A4' });
  const chunks = [];
  
  doc.on('data', chunk => chunks.push(chunk));
  doc.on('end', () => callback(Buffer.concat(chunks)));
  doc.on('error', err => callback(null, err));
  
  // Header
  doc.fontSize(24)
     .fillColor('#00072D')
     .text('INVENTORY REPORT', { align: 'center' });
  
  doc.moveDown();
  
  doc.fontSize(10)
     .fillColor('#666666')
     .text(`Generated on: ${new Date().toLocaleString()}`, { align: 'center' });
  
  doc.moveDown(2);
  
  // Summary Statistics
  if (data.stats) {
    doc.fontSize(16)
       .fillColor('#00072D')
       .text('Summary Statistics', { underline: true });
    
    doc.fontSize(12)
       .fillColor('#000000')
       .text(`Total Products: ${data.stats.totalProducts || 0}`)
       .text(`Total Stock: ${data.stats.totalStock || 0} units`)
       .text(`Low Stock Items: ${data.stats.lowStockItems || 0}`)
       .text(`Out of Stock Items: ${data.stats.outOfStockItems || 0}`)
       .text(`Total Receipts: ${data.stats.totalReceipts || 0}`)
       .text(`Total Deliveries: ${data.stats.totalDeliveries || 0}`);
    
    doc.moveDown();
  }
  
  // Products List
  if (data.products && data.products.length > 0) {
    doc.fontSize(16)
       .fillColor('#00072D')
       .text('Products Inventory', { underline: true });
    
    doc.moveDown(0.5);
    
    data.products.forEach((product, index) => {
      doc.fontSize(10)
         .fillColor('#000000')
         .text(`${index + 1}. ${product.name} (SKU: ${product.sku})`, { indent: 20 })
         .text(`   Stock: ${product.current_stock} | Min: ${product.min_stock} | Category: ${product.category}`, 
               { indent: 30 });
      
      if (product.current_stock <= product.min_stock) {
        doc.fillColor('#FF0000')
           .text(`   ⚠️ LOW STOCK`, { indent: 30 });
        doc.fillColor('#000000');
      }
      
      doc.moveDown(0.3);
    });
  }
  
  doc.moveDown();
  
  // Footer
  doc.fontSize(10)
     .fillColor('#666666')
     .text('This is an automated report generated by Inventory Management System', 
           { align: 'center' });
  
  doc.end();
};

