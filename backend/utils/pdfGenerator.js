import PDFDocument from 'pdfkit';
import { fileURLToPath } from 'url';
import { dirname } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

/**
 * Generate PDF for Receipt (Stock In)
 */
export const generateReceiptPDF = (receipt, product, callback) => {
  const doc = new PDFDocument({ margin: 50, size: 'A4' });
  const chunks = [];
  
  doc.on('data', chunk => chunks.push(chunk));
  doc.on('end', () => callback(Buffer.concat(chunks)));
  doc.on('error', err => callback(null, err));
  
  // Header
  doc.fontSize(24)
     .fillColor('#00072D')
     .text('STOCK RECEIPT', { align: 'center' });
  
  doc.moveDown();
  
  // Receipt Details
  doc.fontSize(12)
     .fillColor('#000000')
     .text(`Receipt ID: #${receipt.id}`, { continued: false })
     .text(`Date: ${new Date(receipt.date).toLocaleDateString('en-US', { 
       year: 'numeric', 
       month: 'long', 
       day: 'numeric',
       hour: '2-digit',
       minute: '2-digit'
     })}`)
     .text(`Status: ${receipt.status.toUpperCase()}`);
  
  doc.moveDown();
  
  // Supplier Information
  doc.fontSize(14)
     .fillColor('#00072D')
     .text('Supplier Information', { underline: true });
  
  doc.fontSize(12)
     .fillColor('#000000')
     .text(`Name: ${receipt.supplier_name}`);
  
  if (receipt.notes) {
    doc.text(`Notes: ${receipt.notes}`);
  }
  
  doc.moveDown();
  
  // Product Information
  doc.fontSize(14)
     .fillColor('#00072D')
     .text('Product Information', { underline: true });
  
  doc.fontSize(12)
     .fillColor('#000000')
     .text(`Product Name: ${product.name || 'N/A'}`)
     .text(`SKU: ${product.sku || 'N/A'}`)
     .text(`Category: ${product.category || 'N/A'}`);
  
  doc.moveDown();
  
  // Transaction Details
  doc.fontSize(14)
     .fillColor('#00072D')
     .text('Transaction Details', { underline: true });
  
  doc.fontSize(12)
     .fillColor('#000000')
     .text(`Quantity Received: ${receipt.quantity} units`);
  
  if (product.current_stock !== undefined) {
    doc.text(`Current Stock After Receipt: ${product.current_stock} units`);
  }
  
  doc.moveDown(2);
  
  // Footer
  doc.fontSize(10)
     .fillColor('#666666')
     .text('This is an automated receipt generated by Inventory Management System', 
           { align: 'center' });
  
  doc.text(`Generated on: ${new Date().toLocaleString()}`, { align: 'center' });
  
  doc.end();
};

